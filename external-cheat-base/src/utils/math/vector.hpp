// ============================================================================
// vector.hpp —— 最基础的 2D/3D/4D 向量结构体
//
// ----------------------------------------------------------------------------
// 🎓 概念卡 ⑯：运算符重载（让自定义类型支持 + - *）
// ----------------------------------------------------------------------------
// 【是什么】
// C++ 允许你给自定义类型重新定义 + - * 等运算符的行为。vec3 定义了
// operator+ 之后，两个 vec3 就能直接相加（每个分量相加），写起来像数学。
//
// 【为什么在这里】游戏里到处是"位置 + 方向"的向量运算（敌人位置减自己位置
// 得到"指向敌人的方向"），重载运算符后代码和数学公式一一对应，可读性大增。
//
// 【最小示例】
//   struct Point { float x, y; };
//   Point operator+(Point a, Point b) { return {a.x + b.x, a.y + b.y}; }
//   Point p = {1,2}; Point q = {3,4};
//   Point r = p + q;   // r = {4, 6}
//
// 【自己动手要点】
// 1) operator+ 的参数和返回类型都可以自己定，但"几个操作数"必须符合
//    语言规定（+ 永远是二元运算）；
// 2) 别滥用：重载后语义要直观（+ 就该是"加"），否则别人看不懂；
// 3) 数学函数（atan2、hypot）来自 <cmath>，是标准库自带的三角/勾股工具。
// ----------------------------------------------------------------------------
//
// 【什么是向量？】
// 游戏里到处是"方向"和"位置"，它们都能用"几个数"表示：
//   - vec3 表示 3D 空间里的一个点或方向（x、y、z 三个坐标）
//   - vec2 表示 2D 屏幕坐标（x、y）
//   - vec4 是 4 个分量（数学上做矩阵运算时用）
//
// 【运算符重载（给 C++ 初学者）】
// vec3 里定义的 operator+ / operator- / operator* 意思是：
// 让两个 vec3 可以直接用 +、-、* 运算。比如：
//   vec3 a{1,2,3}, b{4,5,6};
//   vec3 c = a + b;   // 等于 {5,7,9}，每个分量相加
// 没有这些定义的话，编译器不知道"两个自定义结构体相加"是什么意思。
// ============================================================================

#pragma once

#include <cmath>        // std::atan2、std::hypot
#include <numbers>      // std::numbers::pi_v<float>（圆周率 π）

// 4D 向量（x、y、z、w）。w 通常用于矩阵运算中的齐次坐标
struct vec4
{
	float x, y, z, w;
};

// 3D 向量：游戏世界的坐标/方向
struct vec3
{
	float x, y, z;

	// 向量乘以一个数：每个分量都乘（缩放）
	vec3 operator*(float offset)
	{
		return { this->x * offset, this->y * offset, this->z * offset };
	}
	// 向量加法：对应分量相加
	vec3 operator+(vec3 other)
	{
		return { this->x + other.x, this->y + other.y, this->z + other.z };
	}
	// 向量减法：对应分量相减（两个点相减得到"从一点到另一点的向量"）
	vec3 operator-(vec3 other)
	{
		return { this->x - other.x, this->y - other.y, this->z - other.z };
	}

	// ------------------------------------------------------------------
	// RelativeAngle：把一个方向向量换算成"俯仰角 + 偏航角"（度）
	// ------------------------------------------------------------------
	// 游戏中"朝向"通常用两个角度表示：
	//   - 俯仰角（pitch）：上下看，范围 -90°~+90°
	//   - 偏航角（yaw）：左右转，范围 -180°~+180°
	// 这个函数把 3D 方向向量转成这两个角度。
	// 数学背景：atan2 是"由直角边求角度"的反正切函数；
	// hypot(x,y) 是 sqrt(x²+y²)（斜边长度，数值更稳）。
	// 返回值是 {pitch, yaw, 0}，第三个分量（翻滚角）游戏里一般不用，填 0。
	// 180/π 是把弧度换算成角度（1 弧度 ≈ 57.3 度）。
	vec3 RelativeAngle()
	{
		return {
			std::atan2(-z, std::hypot(x, y)) * (180.0f / std::numbers::pi_v<float>),
			std::atan2(y, x) * (180.0f / std::numbers::pi_v<float>),
			0.0f
		};
	}

};

// 2D 向量：屏幕坐标（x 向右，y 向下）
struct vec2
{
	float x, y;
};
